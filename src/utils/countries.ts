const BY_CODE = new Map(COUNTRIES.map((c) => [c.code, c]));

export function countryByCode(code: string | null | undefined): Country | null {
  if (code === null || code === undefined) return null;
  return BY_CODE.get(code) ?? null;
}

// Lowercase, umlauts and accents folded, so "osterreich", "oesterreich" and
// "Österreich" all match.
export function normalizeCountryQuery(input: string): string {
  return input
    .toLowerCase()
    .replace(/ä/g, 'a').replace(/ö/g, 'o').replace(/ü/g, 'u').replace(/ß/g, 'ss')
    .replace(/ae/g, 'a').replace(/oe/g, 'o').replace(/ue/g, 'u')
    .normalize('NFD').replace(/[̀-ͯ]/g, '')
    .trim();
}

const SEARCH_KEYS = new Map(COUNTRIES.map((c) => [c.code, normalizeCountryQuery(c.name)]));

// Countries whose name contains the query, or whose code equals it.
export function searchCountries(query: string): readonly Country[] {
  const q = normalizeCountryQuery(query);
  if (q.length === 0) return COUNTRIES;
  return COUNTRIES.filter((c) => c.code.toLowerCase() === q || (SEARCH_KEYS.get(c.code) ?? '').includes(q));
}
