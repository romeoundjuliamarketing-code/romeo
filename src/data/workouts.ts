// Returns earned points for a completed workout based on its category rules
export function calculatePoints(workoutId: string, durationMin: number): number {
  const workout = workouts.find(w => w.id === workoutId);
  if (workout === undefined) return 0;
  if (workout.maxPoints !== undefined) return workout.maxPoints;
  return Math.max(1, Math.floor(durationMin / 30)) * workout.pointsPerUnit;
}
